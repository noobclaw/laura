#!/usr/bin/env python3
"""Embed the MP3 sound clips as base64 in prototype3d/assets/sfx.js.

A local page inside an iOS WebView cannot fetch or preload sound files, so the clips travel inside a script
and are decoded with Web Audio on the first touch. Run after changing any file in prototype3d/assets/sfx.
"""
import base64, glob, json, os
here = os.path.dirname(os.path.abspath(__file__)); src = os.path.join(here, "../prototype3d/assets/sfx")
out = {os.path.basename(f)[:-4]: base64.b64encode(open(f, "rb").read()).decode() for f in sorted(glob.glob(src + "/*.mp3"))}
open(os.path.join(here, "../prototype3d/assets/sfx.js"), "w").write("// Generated by tools/make_sfx.py from assets/sfx/*.mp3 (Kenney, CC0). Do not edit.\nwindow.SFX_B64=" + json.dumps(out) + ";\n")
print(len(out), "clips,", sum(len(v) for v in out.values()), "base64 chars")
