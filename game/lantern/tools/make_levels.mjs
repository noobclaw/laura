// Builds prototype3d/levels.js: the shipped level list, computed ahead of time.
// Run: node game/lantern/tools/make_levels.mjs [count]
// Why ahead of time: boards 9 and 10 wide almost never come out with a single solution from random region
// growth (0 in ~45,000 tries each), so they cannot be made on the phone. Here a board is grown at random and
// then repaired: while a second solution exists, one of its cells is handed to a neighbouring region, which
// breaks that solution and leaves the intended one intact. Every kept board is then checked: exactly one
// solution, solvable by the logic solver without guessing, and inside the grade band of its level.
import fs from "node:fs";import path from "node:path";import {fileURLToPath} from "node:url";import {load} from "./harness.mjs";
const {rng,perm,grow,countSolutions,solveSteps,levelSpec}=load();
const dir=path.dirname(fileURLToPath(import.meta.url)),COUNT=+process.argv[2]||300;
const nb4=(k,n)=>{const x=k%n,y=(k-x)/n,o=[];if(x>0)o.push(k-1);if(x<n-1)o.push(k+1);if(y>0)o.push(k-n);if(y<n-1)o.push(k+n);return o};
function other(n,g,sol){const cu=new Array(n).fill(false),ru=new Array(n).fill(false),a=[];let found=null;
  const go=(row,same)=>{if(found)return;if(row===n){if(!same)found=a.slice();return}
    for(let c=0;c<n&&!found;c++){if(cu[c]||(row&&Math.abs(a[row-1]-c)<2))continue;const r=g[row*n+c];if(ru[r])continue;cu[c]=ru[r]=true;a[row]=c;go(row+1,same&&c===sol[row]);cu[c]=ru[r]=false}};
  go(0,true);return found}
function connectedWithout(n,g,k){const id=g[k],cells=[];for(let i=0;i<n*n;i++)if(g[i]===id&&i!==k)cells.push(i);if(!cells.length)return false;
  const seen=new Set([cells[0]]),q=[cells[0]];while(q.length){const c=q.pop();for(const j of nb4(c,n))if(j!==k&&g[j]===id&&!seen.has(j)){seen.add(j);q.push(j)}}return seen.size===cells.length}
function repaired(n,r){const sol=perm(n,r);if(sol.length!==n)return null;const g=grow(n,sol,r);
  for(let it=0;it<600;it++){const a=other(n,g,sol);if(!a)return{n,g,sol};
    const moves=[];for(let y=0;y<n;y++){if(a[y]===sol[y])continue;const k=y*n+a[y];if(!connectedWithout(n,g,k))continue;for(const j of nb4(k,n))if(g[j]!==g[k])moves.push([k,g[j]])}
    if(!moves.length)return null;const m=moves[Math.floor(r()*moves.length)];g[m[0]]=m[1]}
  return null}
const sizes=g=>{const c={};for(const v of g)c[v]=(c[v]||0)+1;return Object.values(c)};
const out=[],seen=new Set();const t0=Date.now();
for(let l=1;l<=COUNT;l++){const sp=levelSpec(l),r=rng(l*7919+sp.n*31+5);let best=null;
  for(let t=0;t<4000;t++){const p=repaired(sp.n,r);if(!p)continue;const key=p.g.join("");if(seen.has(key))continue;
    if(Math.max(...sizes(p.g))>sp.n*sp.n*.34)continue;                       // no single region swallowing the board
    const s=solveSteps(p.n,p.g,[],sp.max);if(!s.solved)continue;p.grade=s.grade;if(s.grade>=sp.min){best=p;break}if(!best||s.grade>best.grade)best=p}
  if(!best)throw new Error("no board for level "+l);
  if(countSolutions(best.n,best.g,2)!==1)throw new Error("not unique: level "+l);
  seen.add(best.g.join(""));out.push(best.n.toString(36)+best.g.map(v=>v.toString(36)).join("")+best.sol.map(v=>v.toString(36)).join("")+best.grade);
  if(l%20===0)console.log("level",l,"n",best.n,"grade",best.grade,((Date.now()-t0)/1000).toFixed(0)+"s")}
const js=`// Generated by tools/make_levels.mjs — do not edit by hand. ${COUNT} boards, each with one solution and solvable by logic alone.
// Format per level: size, then size*size region ids, then the lantern column of each row, then the grade (all base 36).
const LEVELS=${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(dir,"../prototype3d/levels.js"),js);console.log("wrote",out.length,"levels,",js.length,"bytes");
