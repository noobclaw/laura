// Claude QA round 2 (2026-11-28): exact search for "clearable without tools". Replaces solver.mjs.
// Why: solver.mjs keyed states by (board size + tray) and kept a beam of 6, so "not found" proved nothing
// (Codex review, CODEX-RESPONSE-20261128, CR-01). This solver:
//   - keys a state by the full board set, tray groups, every bay (group, required, filled) and the schedule cursor;
//   - delivers a reachable item that an open order needs whenever the choice cannot matter (reachable items of that
//     group <= what the orders still need); when there are more reachable items than needed, WHICH one is delivered
//     is a branch;
//   - branches on stashing every other uncovered item (decoys included: stashing one can uncover items below it);
//   - depth-first with a memo of explored states, so a finished search is exhaustive:
//       solved      -> a pick list, replayed on the real src/session.js from a fresh session;
//       unsolvable  -> every reachable state explored, none clears;
//       unknown     -> budget ran out (NOT evidence either way).
// Rules are mirrored in a small simulator for speed (session resume costs ~5 ms). The mirror is checked against the
// real kernel with random playouts on every stage before searching (--check). Occlusion uses the real occluder lists
// and the real coverage function and thresholds, read through a generated copy of src/session.js (qa/tools/probe/).
// Same content pipeline as the game: balanceStage(neighborhood edition) + applyAmericanArt; default session options.
// Usage: node qa/tools/solver2.mjs [--ms 60000] [--out dir] [--check 30] (--all | 21 22 ...)
