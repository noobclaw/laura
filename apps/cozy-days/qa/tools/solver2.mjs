import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { SortingSession } from '../../src/session.js';
import * as Space from '../../src/spatial.js';
import { ROUND_LIMITS, traySettings } from '../../src/policies.js';
import { applyAmericanArt } from '../../src/art.js';
import { balanceStage, CAMPAIGN_EDITION } from '../../src/campaign.js';

{
  const src = readFileSync(new URL('../../src/session.js', import.meta.url), 'utf8').replaceAll("from './", "from '../../../src/");
  const hook = '  isObstructed(tokenId) {';
  if (!src.includes(hook)) throw new Error('session.js isObstructed changed; update the probe hook');
  const probe = src.replace(hook, '  occludersOf(tokenId) {\n    return this.#occluders(tokenId);\n  }\n  contourOf(tokenId) {\n    return this.#tokens[tokenId].contour;\n  }\n' + hook);
  mkdirSync(new URL('./probe/', import.meta.url), { recursive: true });
  writeFileSync(new URL('./probe/session-probe.mjs', import.meta.url), '// GENERATED by qa/tools/solver2.mjs from src/session.js. QA search only; not shipped.\n' + probe);
}
const { SortingSession: Probe } = await import('./probe/session-probe.mjs');

const argv = process.argv.slice(2);
const opt = (name, fallback) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : fallback);
const BUDGET = Number(opt('--ms', 60000));
const CHECK = Number(opt('--check', 30));
const OUT = opt('--out', new URL('../evidence/solver2/', import.meta.url).pathname);
const stages = argv.includes('--all') ? Array.from({ length: 160 }, (_, i) => i + 1)
  : argv.filter((a, i) => /^\d+$/.test(a) && !['--ms', '--out', '--check'].includes(argv[i - 1])).map(Number);

const loadStage = async n => applyAmericanArt(balanceStage(JSON.parse(await readFile(new URL(`../../data/stage-${String(n).padStart(3, '0')}.json`, import.meta.url), 'utf8')), n, CAMPAIGN_EDITION));
const TRAY = traySettings('flexible').available;
const BAYS = 3;

function model(p) {
  const probe = new Probe(p.stage, p.forms, {});
  const N = p.stage.specimens.length;
  const group = Array.from({ length: N }, (_, i) => probe.tokenInfo(i).group);
  const occ = Array.from({ length: N }, (_, i) => probe.occludersOf(i));
  const schedule = p.stage.shipments.map(s => ({ group: s.group, required: s.quantity }));
  const cover = new Map();
  const obstructed = (t, on) => {
    const above = occ[t].filter(id => on[id]);
    if (!above.length) return false;
    const k = t + ':' + above.join(',');
    let v = cover.get(k);
    if (v === undefined) {
      v = Space.coverageFraction(probe.contourOf(t), above.map(id => probe.contourOf(id)), ROUND_LIMITS.exactOccluders) >= ROUND_LIMITS.obstructionFraction;
      cover.set(k, v);
    }
    return v;
  };
  return { N, group, schedule, obstructed };
}

// ---- rule mirror (default options: 3 bays, first 2 open, flexible tray 5 slots, no grouping, no tools) ----
function initial(m) {
  const s = { on: new Uint8Array(m.N).fill(1), tray: [], bays: [], cursor: 0, phase: 'live' };
  for (let i = 0; i < BAYS; i++) s.bays.push({ open: i < ROUND_LIMITS.initialRequests, group: -1, required: 0, filled: 0 });
  for (let i = 0; i < BAYS; i++) if (s.bays[i].open && s.cursor < m.schedule.length) load(m, s, i);
  return s;
}
const cloneState = s => ({ on: s.on.slice(), tray: s.tray.slice(), bays: s.bays.map(b => ({ ...b })), cursor: s.cursor, phase: s.phase });
function load(m, s, i) {
  const sh = m.schedule[s.cursor++];
  Object.assign(s.bays[i], { group: sh.group, required: sh.required, filled: 0 });
}
function finish(m, s, i) {
  if (s.cursor < m.schedule.length) {
    load(m, s, i);
    const b = s.bays[i];
    for (let c = 0; c < s.tray.length && b.filled < b.required;) {
      if (s.tray[c] === b.group) { s.tray.splice(c, 1); b.filled++; } else c++;
    }
    if (b.filled === b.required) finish(m, s, i);
    return;
  }
  Object.assign(s.bays[i], { group: -1, required: 0, filled: 0 });
  if (s.bays.every(b => b.group === -1)) s.phase = 'done';
}
function destination(s, gr) {
  let chosen = -1;
  s.bays.forEach((b, i) => { if (b.open && b.group === gr && b.filled < b.required && (chosen < 0 || b.filled > s.bays[chosen].filled)) chosen = i; });
  return chosen;
}
const hasImmediateMove = (m, s) => { for (let t = 0; t < m.N; t++) if (s.on[t] && destination(s, m.group[t]) >= 0 && !m.obstructed(t, s.on)) return true; return false; };
function assess(m, s) {
  if (s.phase !== 'live') return;
  if (s.tray.length >= TRAY && !hasImmediateMove(m, s)) s.phase = 'lost';
}
// Returns false when the real kernel would ignore the pick.
function pick(m, s, t) {
  if (s.phase !== 'live' || !s.on[t] || m.obstructed(t, s.on)) return false;
  const d = destination(s, m.group[t]);
  if (d < 0) {
    if (s.tray.length >= TRAY) { s.phase = 'lost'; return true; }
    s.on[t] = 0;
    s.tray.push(m.group[t]);
    assess(m, s);
    return true;
  }
  s.on[t] = 0;
  const b = s.bays[d];
  b.filled++;
  if (b.filled === b.required) finish(m, s, d);
  assess(m, s);
  return true;
}
const key = s => {
  let k = '';
  for (let i = 0; i < s.on.length; i += 6) { let v = 0; for (let j = 0; j < 6 && i + j < s.on.length; j++) v |= s.on[i + j] << j; k += String.fromCharCode(48 + v); }
  return k + '|' + s.tray.slice().sort((a, b) => a - b).join(',') + '|' + s.bays.map(b => `${b.group}:${b.required}:${b.filled}`).join(',') + '|' + s.cursor;
};

// Apply deliveries whose choice cannot matter; return surplus delivery candidates (a real choice).
function settle(m, s, path) {
  for (;;) {
    if (s.phase !== 'live') return [];
    const free = [];
    for (let t = 0; t < m.N; t++) if (s.on[t] && destination(s, m.group[t]) >= 0 && !m.obstructed(t, s.on)) free.push(t);
    if (!free.length) return [];
    const need = new Map();
    for (const b of s.bays) if (b.open && b.group !== -1 && b.filled < b.required) need.set(b.group, (need.get(b.group) ?? 0) + b.required - b.filled);
    const byGroup = new Map();
    for (const t of free) { const gr = m.group[t]; if (!byGroup.has(gr)) byGroup.set(gr, []); byGroup.get(gr).push(t); }
    const forced = [...byGroup].find(([gr, ts]) => ts.length <= need.get(gr));
    if (forced) { pick(m, s, forced[1][0]); path.push(forced[1][0]); continue; }
    return free; // every deliverable group has more reachable items than needed
  }
}

function playoutCheck(m, p, runs, seed) {
  let x = seed >>> 0;
  const rnd = () => ((x = (x * 1664525 + 1013904223) >>> 0) / 2 ** 32);
  for (let run = 0; run < runs; run++) {
    const real = new SortingSession(p.stage, p.forms, {});
    const s = initial(m);
    for (let step = 0; step < 400 && s.phase === 'live'; step++) {
      const board = real.inspect().board;
      const t = board[Math.floor(rnd() * board.length)];
      real.dispatch({ kind: 'collect', tokenId: t });
      pick(m, s, t);
      const r = real.inspect();
      const realTray = r.tray.filter(c => c.tokenId !== null).map(c => m.group[c.tokenId]).sort((a, b) => a - b).join(',');
      const same = r.phase === s.phase && r.cursor === s.cursor && realTray === s.tray.slice().sort((a, b) => a - b).join(',')
        && r.board.length === s.on.reduce((a, v) => a + v, 0)
        && r.bays.every((b, i) => b.group === s.bays[i].group && (b.group === -1 || (b.filled === s.bays[i].filled && b.required === s.bays[i].required)));
      if (!same) return { ok: false, run, step, token: t, real: { phase: r.phase, cursor: r.cursor, tray: realTray, bays: r.bays.map(b => [b.group, b.filled, b.required]) }, mirror: { phase: s.phase, cursor: s.cursor, tray: s.tray, bays: s.bays.map(b => [b.group, b.filled, b.required]) } };
    }
  }
  return { ok: true, runs };
}

async function solve(n) {
  const p = await loadStage(n);
  const m = model(p);
  const check = CHECK ? playoutCheck(m, p, CHECK, n * 7919) : { ok: true, runs: 0 };
  const base = { n, items: m.N, orders: m.schedule.length, mirrorCheck: check };
  if (!check.ok) return { ...base, result: 'mirror-mismatch' };
  const t0 = performance.now();
  const seen = new Set();
  let nodes = 0, timedOut = false, solution = null, deepest = { delivered: -1, path: [] };
  const root = initial(m);
  const rootPath = [];
  const stack = [{ s: root, path: rootPath, surplus: settle(m, root, rootPath) }];
  while (stack.length) {
    if ((nodes & 255) === 0 && performance.now() - t0 > BUDGET) { timedOut = true; break; }
    const { s, path, surplus } = stack.pop();
    if (s.phase === 'done') { solution = path; break; }
    if (s.phase !== 'live') continue;
    const k = key(s);
    if (seen.has(k)) continue;
    seen.add(k);
    nodes++;
    const delivered = s.cursor * 1000 + s.bays.reduce((a, b) => a + b.filled, 0);
    if (delivered > deepest.delivered) deepest = { delivered, path };
    const upcoming = m.schedule.slice(s.cursor).map(x => x.group);
    const open = new Set(s.bays.filter(b => b.group !== -1).map(b => b.group));
    const rank = gr => (open.has(gr) ? -1 : upcoming.includes(gr) ? upcoming.indexOf(gr) : 1e6);
    const moves = [...surplus];
    const delivering = new Set(surplus);
    for (let t = 0; t < m.N; t++) if (s.on[t] && !delivering.has(t) && !m.obstructed(t, s.on)) moves.push(t);
    // Explore deliveries first, then stashes of the soonest-needed groups; push in reverse.
    moves.sort((a, b) => (delivering.has(b) - delivering.has(a)) || rank(m.group[a]) - rank(m.group[b]));
    for (let i = moves.length - 1; i >= 0; i--) {
      const c = cloneState(s);
      if (!pick(m, c, moves[i])) continue;
      const cp = [...path, moves[i]];
      const sur = settle(m, c, cp);
      if (c.phase === 'lost') continue;
      if (c.phase === 'live' && seen.has(key(c))) continue;
      stack.push({ s: c, path: cp, surplus: sur });
    }
  }
  const ms = Math.round(performance.now() - t0);
  Object.assign(base, { nodes, ms });
  // Deep-path check: replay the furthest state the search reached on the real kernel, comparing every step.
  {
    const real = new SortingSession(p.stage, p.forms, {});
    const s = initial(m);
    let mismatch = null;
    deepest.path.forEach((t, step) => {
      if (mismatch) return;
      real.dispatch({ kind: 'collect', tokenId: t });
      pick(m, s, t);
      const r = real.inspect();
      const realTray = r.tray.filter(c => c.tokenId !== null).map(c => m.group[c.tokenId]).sort((a, b) => a - b).join(',');
      const same = r.phase === s.phase && r.cursor === s.cursor && realTray === s.tray.slice().sort((a, b) => a - b).join(',') && r.board.join(',') === [...s.on.keys()].filter(i => s.on[i]).join(',')
        && r.bays.every((b, i) => b.group === s.bays[i].group && (b.group === -1 || b.filled === s.bays[i].filled));
      if (!same) mismatch = { step, token: t };
    });
    const r = real.inspect();
    base.deepPathCheck = { picks: deepest.path.length, ordersDone: r.cursor - r.bays.filter(b => b.group !== -1).length, of: m.schedule.length, ok: !mismatch, ...(mismatch ? { mismatch } : {}) };
    if (mismatch) return { ...base, result: 'mirror-mismatch' };
  }
  if (solution) {
    const r = new SortingSession(p.stage, p.forms, {});
    let stashes = 0;
    for (const id of solution) {
      const before = r.inspect().tray.filter(c => c.tokenId !== null).length;
      r.dispatch({ kind: 'collect', tokenId: id });
      if (r.inspect().tray.filter(c => c.tokenId !== null).length > before) stashes++;
    }
    const ok = r.inspect().phase === 'done';
    return { ...base, result: ok ? 'solved' : 'replay-failed', picks: solution.length, stashes, solution };
  }
  return { ...base, result: timedOut ? 'unknown' : 'unsolvable' };
}

await mkdir(OUT, { recursive: true });
for (const n of stages) {
  const r = await solve(n);
  await writeFile(`${OUT}stage-${String(n).padStart(3, '0')}.json`, JSON.stringify(r));
  const { solution, ...brief } = r;
  console.log(JSON.stringify(brief));
}
