export function translator(locale) {
  const column = locale === 'en' ? 2 : locale === 'zh-TW' ? 1 : 0;
  return (key, values = {}) => (rows[key]?.[column] ?? key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}
export function meritTitle(key, locale) {
  const name = meritNames[key]?.[locale === 'en' ? 1 : 0] ?? key;
  if (locale !== 'zh-TW') return name;
  const characters = {
    装: '裝',
    满: '滿',
    归: '歸',
    关: '關',
    从: '從',
    两: '兩',
    级: '級',
    试: '試',
    获: '獲',
    险: '險',
    为: '為',
    游: '遊'
  };
  return [...name].map(character => characters[character] ?? character).join('');
}
